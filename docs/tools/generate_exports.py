"""Generate static import stubs from the public packages' lazy export tables.

Run `uv run python docs/tools/generate_exports.py` after changing a table.
Use `--check` to verify that the committed stubs match it.
"""

from __future__ import annotations

import ast
from pathlib import Path
import sys

PACKAGES = (
    "yoke.agent",
    "yoke.agent.loop",
    "yoke.agent.compaction",
    "yoke.ai",
    "yoke.ai.providers",
)
ROOT = Path(__file__).resolve().parents[2]


def generate(package: str) -> str:
    """Read the literal table without importing any runtime dependencies."""
    path = ROOT / "src" / package.replace(".", "/") / "__init__.py"
    tree = ast.parse(path.read_text(encoding="utf-8"))
    table = next(
        ast.literal_eval(node.value)
        for node in tree.body
        if isinstance(node, ast.Assign)
        and any(
            isinstance(target, ast.Name) and target.id == "_LAZY_EXPORTS"
            for target in node.targets
        )
    )
    lines = [
        '"""Generated by docs/tools/generate_exports.py; edit the lazy table instead."""',
        "",
        "# ruff: noqa: F401",
        "",
    ]
    for name, target in table.items():
        module, attribute = (target, name) if isinstance(target, str) else target
        lines.append(f"from {module} import {attribute} as {name}")
    all_type = next(
        node.value.func.id
        for node in tree.body
        if isinstance(node, ast.Assign)
        and any(
            isinstance(target, ast.Name) and target.id == "__all__"
            for target in node.targets
        )
        and isinstance(node.value, ast.Call)
        and isinstance(node.value.func, ast.Name)
    )
    annotation = "list[str]" if all_type == "list" else "tuple[str, ...]"
    lines.extend(["", f"__all__: {annotation}", ""])
    return "\n".join(lines)


def main() -> None:
    """Write stubs or check that generation produces no changes."""
    for package in PACKAGES:
        stub = ROOT / "src" / package.replace(".", "/") / "__init__.pyi"
        expected = generate(package)
        if "--check" in sys.argv:
            if ast.dump(ast.parse(stub.read_text(encoding="utf-8"))) != ast.dump(
                ast.parse(expected)
            ):
                raise SystemExit(f"Stale export stub: {stub}")
        else:
            stub.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()
